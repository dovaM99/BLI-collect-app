/** Generate Metro's static image imports and human-readable attribution list. */
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const manifest = JSON.parse(readFileSync(resolve(root, 'docs/beta-photo-sources.json'), 'utf8'));
if (manifest.photos.length !== 100) throw new Error('The beta requires exactly 100 photos.');
const seen = new Set();
const hashes = new Set();
const records = manifest.photos.map((photo) => {
  if (seen.has(photo.id)) throw new Error(`Duplicate photo ID: ${photo.id}`);
  seen.add(photo.id);
  if (!/^images\/[a-zA-Z0-9_./-]+\.webp$/.test(photo.localPath) || photo.localPath.includes('..')) {
    throw new Error(`Invalid local path: ${photo.localPath}`);
  }
  const bytes = readFileSync(resolve(root, photo.localPath));
  const hash = createHash('sha256').update(bytes).digest('hex');
  if (hash !== photo.sha256 || hashes.has(hash)) throw new Error(`Changed or duplicate photo: ${photo.id}`);
  hashes.add(hash);
  for (const key of ['title', 'author', 'license', 'licenseUrl', 'sourceUrl', 'modifications']) {
    if (!photo[key]?.trim()) throw new Error(`Missing ${key}: ${photo.id}`);
  }
  const { localPath, downloadUrl, originalUrl, originalSha1, retrievedAt, width, height, bytes: size, ...metadata } = photo;
  return `  { ...${JSON.stringify(metadata)}, image: require(${JSON.stringify(`../../${localPath}`)}) },`;
});
writeFileSync(resolve(root, 'src/data/betaPhotos.ts'), [
  '// Generated by node scripts/build-beta-photos.mjs. Edit docs/beta-photo-sources.json instead.',
  "import type { ImageSourcePropType } from 'react-native';",
  '',
  'export type BetaPhoto = {',
  '  id: string; title: string; author: string; category: string;',
  '  commonsPageId: number; sourceUrl: string; license: string; licenseUrl: string;',
  '  modifications: string; sha256: string; image: ImageSourcePropType;',
  '};',
  '',
  'export const betaPhotos: BetaPhoto[] = [',
  ...records,
  '];',
  '',
].join('\n'));

const md = (text) => String(text).replace(/[\[\]<>|]/g, ' ').replace(/\s+/g, ' ');
writeFileSync(resolve(root, 'docs/beta-photo-sources.md'), [
  '# Sources des 100 photos de la bêta',
  '',
  `Lot : \`${manifest.packId}\`. Métadonnées relevées le ${manifest.retrievedAt.slice(0, 10)}.`,
  '',
  'Le masque déjà présent est conservé. Les 99 autres photos ont été téléchargées depuis Wikimedia Commons, puis réduites à 1 280 pixels maximum sur leur plus grand côté et encodées en WebP, sans recadrage. Les transformations sont indiquées pour chaque fichier. Les versions distribuées restent sous leur licence respective : ces images sont sous licence libre, et non dépourvues de droits.',
  '',
  'Les titres, auteurs et licences sont également accessibles hors ligne sous chaque photo dans l’application. Les liens vers les pages source et les licences demandent une connexion. Le JSON voisin contient les URL de téléchargement, dimensions et empreintes des fichiers.',
  '',
  ...manifest.photos.flatMap((p, i) => [
    `## ${String(i + 1).padStart(3, '0')} — ${md(p.title)}`,
    '',
    `- Fichier : [${p.localPath}](../${p.localPath})`,
    `- Auteur : ${md(p.author)}`,
    `- Licence : [${md(p.license)}](${p.licenseUrl})`,
    `- Source : [Wikimedia Commons](${p.sourceUrl})`,
    `- Transformations : ${md(p.modifications)}`,
    '',
  ]),
].join('\n'));
const html = (text) => String(text).replace(/[&<>"']/g, (char) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[char]);
const cards = manifest.photos.map((photo, index) => `
  <article>
    <div class="photo"><img src="../${html(photo.localPath)}" alt="${html(photo.title)}" loading="lazy"><span>${String(index + 1).padStart(3, '0')}</span></div>
    <div class="caption"><small>${html(photo.category)}</small><h2>${html(photo.title)}</h2>
    <p>${html(photo.author)}</p><a href="${html(photo.sourceUrl)}">Source Wikimedia</a> · <a href="${html(photo.licenseUrl)}">${html(photo.license)}</a></div>
  </article>`).join('');
writeFileSync(resolve(root, 'docs/beta-photo-gallery.html'), `<!doctype html>
<html lang="fr"><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>BLI Collect — les 100 photos de la bêta</title>
<style>
*{box-sizing:border-box}body{margin:0;background:#f6f3ed;color:#172f3a;font:15px/1.5 system-ui,sans-serif}
header{padding:48px max(24px,5vw);background:#173d42;color:#fff}header small{letter-spacing:.15em;color:#ffcc85}
h1{font-size:clamp(30px,5vw,52px);line-height:1.12;max-width:900px;margin:12px 0}header p{max-width:760px;color:#dce9e6}
main{padding:32px max(24px,5vw);display:grid;grid-template-columns:repeat(auto-fill,minmax(250px,1fr));gap:24px}
article{background:white;border:1px solid #e0e4df;border-radius:14px;overflow:hidden}.photo{height:230px;background:#e5ece8;position:relative}
img{width:100%;height:100%;object-fit:contain}.photo span{position:absolute;top:10px;left:10px;background:#173d42;color:#fff;padding:3px 9px;border-radius:5px}
.caption{padding:16px}small{text-transform:uppercase;font-size:11px;letter-spacing:.08em}h2{font-size:15px;line-height:1.4;margin:6px 0;overflow-wrap:anywhere}
.caption p{font-size:12px;color:#536861;margin:8px 0}a{color:#25605b;font-size:12px}footer{padding:20px max(24px,5vw) 48px;color:#536861}
</style>
<header><small>Bantu Languages Initiative · Bêta</small><h1>100 photos pour les collecteurs</h1>
<p>Le masque Iyoba et 99 nouvelles photographies du Congo et d’Afrique. Un exercice par photo, avec des thèmes alternés : vie quotidienne, alimentation, agriculture, transports, paysages et patrimoine.</p>
<p>Les images sont disponibles hors connexion dans l’application. Réponses en lingala, kituba ou kikongo ; consigne en français ou en anglais.</p></header>
<main>${cards}</main>
<footer>Photos sous leurs licences respectives. Versions converties en WebP ; les 99 nouvelles images ont aussi été redimensionnées sans recadrage. Les liens Source et Licence nécessitent Internet. <a href="beta-photo-sources.md">Crédits détaillés</a>.</footer>
</html>\n`);
console.log(`Generated ${records.length} static photo imports, attribution entries, and gallery cards.`);
